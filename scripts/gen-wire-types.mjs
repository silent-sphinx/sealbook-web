// Writes src/lib/wire.gen.ts from the wire schema in the pinned sealbook checkout.
// Run with `npm run wire`; CI fails if the checked-in file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "../sealbook/crates/sealbook-protocol/schema/wire.json");
const target = join(root, "src/lib/wire.gen.ts");

// A $ref beside a description would otherwise be emitted as a second copy of
// the referenced type.
function wrapDescribedRefs(node) {
  if (Array.isArray(node)) return node.map(wrapDescribedRefs);
  if (node === null || typeof node !== "object") return node;
  const out = Object.fromEntries(
    Object.entries(node).map(([key, value]) => [key, wrapDescribedRefs(value)]),
  );
  if (out.$ref && Object.keys(out).length > 1) {
    const { $ref, ...rest } = out;
    return { ...rest, allOf: [{ $ref }] };
  }
  return out;
}

const schema = wrapDescribedRefs(JSON.parse(readFileSync(source, "utf8")));
delete schema.description;
const generated = await compile(schema, "WireTypes", {
  additionalProperties: false,
  unreachableDefinitions: true,
  bannerComment:
    "// Generated by scripts/gen-wire-types.mjs from sealbook-protocol/schema/wire.json. Do not edit.",
});
const ts = generated.replace(/export interface SealbookWireTypes \{\n  \[k: string\]: unknown;\n\}\n/, "");
writeFileSync(target, ts);
